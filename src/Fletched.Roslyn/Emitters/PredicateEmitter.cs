using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Fletched.Roslyn.Pipeline;

namespace Fletched.Roslyn.Emitters;

/// <summary>
/// Generates the complete C# source file for a predicate:
/// SlotId enum, State struct, Result record, and Execute IEnumerable method.
/// </summary>
public sealed class PredicateEmitter
{
    private readonly PredicateModel _model;
    private readonly PlanProgram _plan;
    private readonly bool _generateLegacyNames;
    private readonly string _generatedName;
    private readonly string _resultTypeName;
    private readonly string _executeMethodName;
    private readonly string _contextTypeName;

    // Ordered slot list: (variableName, typeName, slot index)
    private readonly List<(string Name, string TypeName, int Slot)> _slots;
    private readonly List<CallEmitInfo> _calls = [];
    private int _nextCallToEmit;

    // Label → unique integer id for switch dispatch
    private readonly Dictionary<string, int> _labelIds = new();
    private int _labelIdCounter;

    private sealed record CallEmitInfo(
        int Id,
        string EnumeratorVar,
        string ActiveVar,
        string ProducedVar,
        string ResultTypeName);

    private string GeneratedName => _generatedName;

    private string ResultTypeName => _resultTypeName;

    private string ExecuteMethodName => _executeMethodName;

    public PredicateEmitter(PredicateModel model, PlanProgram plan, bool generateLegacyNames)
    {
        _model = model;
        _plan = plan;
        _generateLegacyNames = generateLegacyNames;
        _generatedName = _generateLegacyNames
            ? _model.Name
            : $"{_model.Name}Arity{_model.Arity}";
        _resultTypeName = _generateLegacyNames
            ? $"{_model.Name}Result"
            : $"{_generatedName}Result";
        _executeMethodName = $"ExecuteArity{_model.Arity}";
        _contextTypeName = SourceSymbolHelpers.GetContextTypeName(_model.Symbol);

        var slotTypes = plan.SlotMap.ToDictionary(
            kv => kv.Value,
            kv => kv.Key.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
        var slotNames = plan.SlotMap.ToDictionary(kv => kv.Value, kv => kv.Key.Name);

        foreach (PlanBlock block in new[] { plan.Entry }.Concat(plan.Blocks))
        {
            foreach (PlanInstruction instruction in block.Instructions)
            {
                CollectSlots(instruction, slotNames, slotTypes);
                if (instruction is CallInstr call)
                {
                    int callId = _calls.Count;
                    _calls.Add(new CallEmitInfo(
                        callId,
                        EnumeratorVar: $"_callEnum_{callId}",
                        ActiveVar: $"_callActive_{callId}",
                        ProducedVar: $"_callProduced_{callId}",
                        ResultTypeName: GetCallResultTypeName(call)));
                }
            }
        }

        _slots = slotTypes
            .OrderBy(kv => kv.Key)
            .Select(kv => (ResolveSlotName(slotNames, kv.Key), kv.Value, kv.Key))
            .ToList();

        // Assign integer ids to all labels
        var allBlocks = new[] { plan.Entry }.Concat(plan.Blocks);
        foreach (PlanBlock block in allBlocks)
        {
            _labelIds[block.Label] = _labelIdCounter++;
        }
    }

    public string Emit()
    {
        var ctx = new EmitContext(_model.Name, GeneratedName);

        ctx.AppendLine($"// <auto-generated />");
        ctx.AppendLine($"#nullable enable");
        ctx.AppendLine($"#pragma warning disable CS0164, CS0162, CS8600, CS8618, CS8625");
        ctx.AppendLine();

        SourceSymbolHelpers.OpenDeclarationScope(ctx, _model.Symbol);

        EmitSlotIdEnum(ctx);
        ctx.AppendLine();
        EmitStateStruct(ctx);
        ctx.AppendLine();
        EmitResultRecord(ctx);
        ctx.AppendLine();
        EmitPredicatePartial(ctx);
        SourceSymbolHelpers.CloseDeclarationScope(ctx, _model.Symbol);
        EmitModuleQueryWrapper(ctx);

        return ctx.Code.ToString();
    }

    private void EmitSlotIdEnum(EmitContext ctx)
    {
        ctx.AppendLine($"internal enum {ctx.SlotIdTypeName}");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            foreach (var (name, _, slot) in _slots)
                ctx.AppendLine($"{Capitalize(name)} = {slot},");
        }
        ctx.AppendLine("}");
    }

    private void EmitStateStruct(EmitContext ctx)
    {
        ctx.AppendLine($"internal struct {ctx.StateTypeName}");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            foreach (var (name, typeName, _) in _slots)
            {
                ctx.AppendLine($"public {typeName} {name};");
                ctx.AppendLine($"public bool {name}_bound;");
            }
            // Trail — heap class; ref struct may hold a reference type field
            ctx.AppendLine($"public global::Fletched.Core.Runtime.Trail Trail;");
            ctx.AppendLine();
            ctx.AppendLine($"public static {ctx.StateTypeName} Create()");
            ctx.AppendLine("{");
            using (ctx.Indent())
            {
                ctx.AppendLine($"var s = new {ctx.StateTypeName}();");
                ctx.AppendLine("s.Trail = new global::Fletched.Core.Runtime.Trail(256);");
                ctx.AppendLine("return s;");
            }
            ctx.AppendLine("}");
            ctx.AppendLine();
            // Unwind method
            EmitUnwindMethod(ctx);
        }
        ctx.AppendLine("}");
    }

    private void EmitUnwindMethod(EmitContext ctx)
    {
        ctx.AppendLine($"public void Unwind(int targetTop)");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine("while (Trail.Top > targetTop)");
            ctx.AppendLine("{");
            using (ctx.Indent())
            {
                ctx.AppendLine("var _entry = Trail.PopEntry();");
                ctx.AppendLine("switch (_entry.Slot)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    foreach (var (name, _, slot) in _slots)
                    {
                        ctx.AppendLine($"case {slot}: {name}_bound = _entry.WasBound; break;");
                    }
                }
                ctx.AppendLine("}");
            }
            ctx.AppendLine("}");
        }
        ctx.AppendLine("}");
    }

    private void EmitResultRecord(EmitContext ctx)
    {
        // Only terminal variables appear in the result
        var terminals = _model.Parameters.Select(p => (p.Name,
            TypeName: p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))).ToList();

        string fields = string.Join(", ", terminals.Select(t => $"{t.TypeName} {t.Name}"));
        ctx.AppendLine($"public readonly record struct {ResultTypeName}({fields});");
    }

    private void EmitPredicatePartial(EmitContext ctx)
    {
        ctx.AppendLine($"partial record struct {_model.Name}");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            EmitPredicateCallHelpers(ctx);

            if (_generateLegacyNames)
            {
                ctx.AppendLine($"public System.Collections.Generic.IEnumerable<{ResultTypeName}> Execute({_contextTypeName} ctx, global::Fletched.Core.Performance.IExecutionObserver? observer = null)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                    ctx.AppendLine($"return {ExecuteMethodName}(ctx, observer);");
                ctx.AppendLine("}");
                ctx.AppendLine();
            }
            EmitExecuteMethod(ctx);
        }
        ctx.AppendLine("}");
    }

    private void EmitPredicateCallHelpers(EmitContext ctx)
    {
        CallExpr[] callExpressions = CollectCallExpressions(_model.Body)
            .Where(call => !SymbolEqualityComparer.Default.Equals(call.PredicateType, _model.Symbol))
            .GroupBy(call => $"{call.PredicateType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}/{call.Arity}", StringComparer.Ordinal)
            .Select(group => group.First())
            .ToArray();

        if (callExpressions.Length == 0)
            return;

        foreach (CallExpr call in callExpressions)
        {
            IMethodSymbol bodyMethod = ResolvePredicateBodyMethod(call.PredicateType, call.Arity);
            string parameterList = string.Join(", ",
                bodyMethod.Parameters.Select((parameter, index) =>
                    $"global::Fletched.Core.LogicExpr<{GetPredicateParameterValueType(parameter).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}> arg{index}"));

            ctx.AppendLine($"private static global::Fletched.Core.LogicExpr<bool> {call.PredicateType.Name}({parameterList}) => default;");
        }

        ctx.AppendLine();
    }

    private void EmitExecuteMethod(EmitContext ctx)
    {
        _nextCallToEmit = 0;
        ctx.AppendLine($"public System.Collections.Generic.IEnumerable<{ResultTypeName}> {ExecuteMethodName}({_contextTypeName} ctx, global::Fletched.Core.Performance.IExecutionObserver? observer = null)");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"var state = {ctx.StateTypeName}.Create();");
            ctx.AppendLine($"var cps = new System.Collections.Generic.Stack<global::Fletched.Core.Runtime.ChoicePoint>();");

            // Emit index variables
            EmitIndexVarDecls(ctx);
            EmitCallVarDecls(ctx);

            ctx.AppendLine($"goto L_{_plan.Entry.Label};");
            ctx.AppendLine();

            // Fail label
            ctx.AppendLine("Fail:");
            using (ctx.Indent())
                ctx.AppendLine("goto Resume;");
            ctx.AppendLine();

            // Resume label
            ctx.AppendLine("Resume:");
            using (ctx.Indent())
            {
                ctx.AppendLine("if (!cps.TryPop(out var _cp))");
                using (ctx.Indent())
                    ctx.AppendLine("goto End;");
                ctx.AppendLine("state.Unwind(_cp.TrailTop);");
                ctx.AppendMetricIncrement("BacktrackCount");
                ctx.AppendLine("observer?.OnBacktrack();");
                ctx.AppendLine("switch (_cp.LabelId)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    foreach (var kv in _labelIds)
                        ctx.AppendLine($"case {kv.Value}: goto L_{kv.Key};");
                    ctx.AppendLine("default: goto End;");
                }
                ctx.AppendLine("}");
            }
            ctx.AppendLine();

            // Success label
            ctx.AppendLine("Success:");
            using (ctx.Indent())
            {
                string projection = string.Join(", ", _model.Parameters.Select(p => $"state.{p.Name}"));
                ctx.AppendLine($"yield return new {ResultTypeName}({projection});");
                ctx.AppendLine("goto Resume;");
            }
            ctx.AppendLine();

            // Emit all blocks
            var allBlocks = new[] { _plan.Entry }.Concat(_plan.Blocks);
            foreach (PlanBlock block in allBlocks)
                EmitBlock(block, ctx);

            ctx.AppendLine();
            ctx.AppendLine("End:");
            using (ctx.Indent())
                ctx.AppendLine("yield break;");
        }
        ctx.AppendLine("}");
    }

    private void EmitModuleQueryWrapper(EmitContext ctx)
    {
        INamedTypeSymbol? moduleRoot = SourceSymbolHelpers.GetModuleRoot(_model.Symbol);
        if (moduleRoot is null || _model.Symbol.DeclaredAccessibility != Accessibility.Public)
            return;

        string moduleDeclaration = SourceSymbolHelpers.GetTypeDeclaration(moduleRoot);
        string predicateTypeName = _model.Symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string resultTypeName = SourceSymbolHelpers.GetQualifiedSiblingTypeName(_model.Symbol, ResultTypeName);
        string wrapperName = _generateLegacyNames
            ? $"Query_{_model.Name}"
            : $"Query_{GeneratedName}";

        ctx.AppendLine();
        ctx.AppendLine(moduleDeclaration);
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"public static System.Collections.Generic.IEnumerable<{resultTypeName}> {wrapperName}({_contextTypeName} ctx, global::Fletched.Core.Performance.IExecutionObserver? observer = null)");
            ctx.AppendLine("{");
            using (ctx.Indent())
                ctx.AppendLine($"return default({predicateTypeName}).{ExecuteMethodName}(ctx, observer);");
            ctx.AppendLine("}");
        }
        ctx.AppendLine("}");
    }

    private void EmitIndexVarDecls(EmitContext ctx)
    {
        // Collect all index vars from all blocks
        var indexVars = new HashSet<string>();
        var indexedVars = new HashSet<string>();
        foreach (PlanBlock block in new[] { _plan.Entry }.Concat(_plan.Blocks))
        {
            foreach (PlanInstruction instr in block.Instructions)
            {
                if (instr is IndexInitInstr init)
                {
                    indexVars.Add(init.IndexVar);
                    if (init.IndexedLookup is not null)
                        indexedVars.Add(init.IndexVar);
                }
                if (instr is IndexIncrInstr incr) indexVars.Add(incr.IndexVar);
                if (instr is LoopBindInstr bind) indexVars.Add(bind.IndexVar);
            }
            if (block.Terminator is LoopCheckTerm lc) indexVars.Add(lc.IndexVar);
        }
        foreach (string v in indexVars)
        {
            ctx.AppendLine($"int {v} = 0;");
            if (indexedVars.Contains(v))
                ctx.AppendLine($"int[]? {IndexMatchesVar(v)} = null;");
        }
    }

    private void EmitCallVarDecls(EmitContext ctx)
    {
        foreach (CallEmitInfo call in _calls)
        {
            ctx.AppendLine($"System.Collections.Generic.IEnumerator<{call.ResultTypeName}>? {call.EnumeratorVar} = null;");
            ctx.AppendLine($"bool {call.ActiveVar} = false;");
            ctx.AppendLine($"bool {call.ProducedVar} = false;");
        }
    }

    private void EmitBlock(PlanBlock block, EmitContext ctx)
    {
        ctx.AppendLine($"L_{block.Label}:");
        using (ctx.Indent())
        {
            foreach (PlanInstruction instr in block.Instructions)
                EmitInstruction(instr, block.Label, ctx);
            EmitTerminator(block.Terminator, block.Label, ctx);
        }
        ctx.AppendLine();
    }

    private void EmitInstruction(PlanInstruction instr, string blockLabel, EmitContext ctx)
    {
        switch (instr)
        {
            case UnifyInstr u:
                EmitUnify(u, ctx);
                break;

            case ConstraintInstr c:
                EmitConstraint(c, ctx);
                break;

            case AssignInstr a:
                ctx.AppendLine($"state.{SlotName(a.Slot)} = {EmitValue(a.Value)};");
                ctx.AppendLine($"state.{SlotName(a.Slot)}_bound = true;");
                break;

            case IndexInitInstr init:
                EmitIndexInit(init, ctx);
                break;

            case LoopBindInstr bind:
                EmitLoopBind(bind, ctx);
                break;

            case IndexIncrInstr incr:
                ctx.AppendLine($"{incr.IndexVar}++;");
                break;

            case CompInstr comp:
                EmitComp(comp, ctx);
                break;

            case CallInstr call:
                EmitCall(call, blockLabel, ctx);
                break;

            case NotInstr not:
                EmitNot(not, ctx);
                break;
        }
    }

    private void EmitIndexInit(IndexInitInstr init, EmitContext ctx)
    {
        string tableProp = TablePropertyName(init.FactType);
        string matchesVar = IndexMatchesVar(init.IndexVar);

        if (init.IndexedLookup is null)
        {
            ctx.AppendLine($"{init.IndexVar} = 0;");
            ctx.AppendMetricIncrement("FactScans");
            ctx.AppendLine($"observer?.OnFactScan(\"{init.FactType.Name}\");");
            return;
        }

        switch (init.IndexedLookup.Key)
        {
            case SlotValue slot:
            {
                string slotName = SlotName(slot.Slot);
                ctx.AppendLine($"{init.IndexVar} = 0;");
                ctx.AppendLine($"if (state.{slotName}_bound)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    ctx.AppendMetricIncrement("IndexHits");
                    ctx.AppendLine($"observer?.OnIndexHit(\"{init.FactType.Name}\");");
                    ctx.AppendLine($"if (!ctx.{tableProp}.TryGetIndex(\"{init.IndexedLookup.MemberName}\", state.{slotName}, out {matchesVar})) goto Fail;");
                }
                ctx.AppendLine("}");
                ctx.AppendLine("else");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    ctx.AppendLine($"{matchesVar} = null;");
                    ctx.AppendMetricIncrement("FactScans");
                    ctx.AppendLine($"observer?.OnFactScan(\"{init.FactType.Name}\");");
                }
                ctx.AppendLine("}");
                return;
            }

            default:
                ctx.AppendLine($"{init.IndexVar} = 0;");
                ctx.AppendMetricIncrement("IndexHits");
                ctx.AppendLine($"observer?.OnIndexHit(\"{init.FactType.Name}\");");
                ctx.AppendLine($"if (!ctx.{tableProp}.TryGetIndex(\"{init.IndexedLookup.MemberName}\", {EmitValue(init.IndexedLookup.Key)}, out {matchesVar})) goto Fail;");
                return;
        }
    }

    private void EmitLoopBind(LoopBindInstr bind, EmitContext ctx)
    {
        string tableProp = TablePropertyName(bind.FactType);
        string slotName = SlotName(bind.Slot);

        if (bind.IndexedLookup is null)
        {
            ctx.AppendLine($"state.{slotName} = ctx.{tableProp}.Data[{bind.IndexVar}];");
            ctx.AppendLine($"state.{slotName}_bound = true;");
            return;
        }

        string matchesVar = IndexMatchesVar(bind.IndexVar);
        switch (bind.IndexedLookup.Key)
        {
            case SlotValue keySlot:
            {
                string keySlotName = SlotName(keySlot.Slot);
                ctx.AppendLine($"if (state.{keySlotName}_bound)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    ctx.AppendLine($"state.{slotName} = ctx.{tableProp}.Data[{matchesVar}![{bind.IndexVar}]];");
                    ctx.AppendLine($"state.{slotName}_bound = true;");
                }
                ctx.AppendLine("}");
                ctx.AppendLine("else");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    ctx.AppendLine($"state.{slotName} = ctx.{tableProp}.Data[{bind.IndexVar}];");
                    ctx.AppendLine($"state.{slotName}_bound = true;");
                }
                ctx.AppendLine("}");
                return;
            }

            default:
                ctx.AppendLine($"state.{slotName} = ctx.{tableProp}.Data[{matchesVar}![{bind.IndexVar}]];");
                ctx.AppendLine($"state.{slotName}_bound = true;");
                return;
        }
    }

    private void EmitLoopCheck(LoopCheckTerm loopCheck, EmitContext ctx)
    {
        string tableProp = TablePropertyName(loopCheck.FactType);

        if (loopCheck.IndexedLookup is null)
        {
            ctx.AppendLine($"if ({loopCheck.IndexVar} >= ctx.{tableProp}.Data.Length) goto Fail;");
            ctx.AppendLine($"goto L_{loopCheck.BodyLabel};");
            return;
        }

        string matchesVar = IndexMatchesVar(loopCheck.IndexVar);
        switch (loopCheck.IndexedLookup.Key)
        {
            case SlotValue slot:
            {
                string slotName = SlotName(slot.Slot);
                ctx.AppendLine($"if (state.{slotName}_bound)");
                ctx.AppendLine("{");
                using (ctx.Indent())
                    ctx.AppendLine($"if ({matchesVar} is null || {loopCheck.IndexVar} >= {matchesVar}.Length) goto Fail;");
                ctx.AppendLine("}");
                ctx.AppendLine("else");
                ctx.AppendLine("{");
                using (ctx.Indent())
                    ctx.AppendLine($"if ({loopCheck.IndexVar} >= ctx.{tableProp}.Data.Length) goto Fail;");
                ctx.AppendLine("}");
                ctx.AppendLine($"goto L_{loopCheck.BodyLabel};");
                return;
            }

            default:
                ctx.AppendLine($"if ({matchesVar} is null || {loopCheck.IndexVar} >= {matchesVar}.Length) goto Fail;");
                ctx.AppendLine($"goto L_{loopCheck.BodyLabel};");
                return;
        }
    }

    private void EmitCall(CallInstr call, string blockLabel, EmitContext ctx)
    {
        CallEmitInfo callInfo = _calls[_nextCallToEmit++];
        string predTypeName = call.PredicateType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string resultVar = $"_callResult_{callInfo.Id}";

        ctx.AppendLine($"if (!{callInfo.ActiveVar})");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendMetricIncrement("PredicateInvocations");
            ctx.AppendLine($"observer?.OnPredicateInvocation(\"{call.PredicateType.Name}\");");
            ctx.AppendLine($"global::Fletched.Core.Runtime.RecursionGuard.EnterPredicateInvocation(ctx, \"{call.PredicateType.Name}\", observer);");
            ctx.AppendMetricIncrement("RecursiveInvocations");
            ctx.AppendDirective("#if METRICS");
            ctx.AppendLine("global::Fletched.Core.Performance.EngineMetrics.RecursiveDepth.Record(global::Fletched.Core.Runtime.RecursionGuard.GetCurrentDepth(ctx));");
            ctx.AppendDirective("#endif");
            ctx.AppendLine("try");
            ctx.AppendLine("{");
            using (ctx.Indent())
                ctx.AppendLine($"{callInfo.EnumeratorVar} = default({predTypeName}).ExecuteArity{call.Arity}(ctx, observer).GetEnumerator();");
            ctx.AppendLine("}");
            ctx.AppendLine("catch");
            ctx.AppendLine("{");
            using (ctx.Indent())
            {
                ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.ExitPredicateInvocation(ctx);");
                ctx.AppendLine("throw;");
            }
            ctx.AppendLine("}");
            ctx.AppendLine($"{callInfo.ActiveVar} = true;");
            ctx.AppendLine($"{callInfo.ProducedVar} = false;");
        }
        ctx.AppendLine("}");
        ctx.AppendLine("else");
        ctx.AppendLine("{");
        using (ctx.Indent())
            ctx.AppendMetricIncrement("PredicateInvocationResumes");
        ctx.AppendLine("}");

        string movedNextVar = $"_callMovedNext_{callInfo.Id}";
        ctx.AppendLine($"bool {movedNextVar};");
        ctx.AppendLine("try");
        ctx.AppendLine("{");
        using (ctx.Indent())
            ctx.AppendLine($"{movedNextVar} = {callInfo.EnumeratorVar} is not null && {callInfo.EnumeratorVar}.MoveNext();");
        ctx.AppendLine("}");
        ctx.AppendLine("catch");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"{callInfo.EnumeratorVar}?.Dispose();");
            ctx.AppendLine($"{callInfo.EnumeratorVar} = null;");
            ctx.AppendLine($"{callInfo.ActiveVar} = false;");
            ctx.AppendLine($"{callInfo.ProducedVar} = false;");
            ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.ExitPredicateInvocation(ctx);");
            ctx.AppendLine("throw;");
        }
        ctx.AppendLine("}");

        ctx.AppendLine($"if (!{movedNextVar})");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendMetricIncrement("PredicateInvocationExhaustions");
            ctx.AppendLine($"if (!{callInfo.ProducedVar})");
            ctx.AppendLine("{");
            using (ctx.Indent())
                ctx.AppendMetricIncrement("PredicateInvocationFailures");
            ctx.AppendLine("}");
            ctx.AppendLine($"{callInfo.EnumeratorVar}?.Dispose();");
            ctx.AppendLine($"{callInfo.EnumeratorVar} = null;");
            ctx.AppendLine($"{callInfo.ActiveVar} = false;");
            ctx.AppendLine($"{callInfo.ProducedVar} = false;");
            ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.ExitPredicateInvocation(ctx);");
            ctx.AppendLine("goto Fail;");
        }
        ctx.AppendLine("}");

        ctx.AppendLine($"var {resultVar} = {callInfo.EnumeratorVar}.Current;");
        ctx.AppendLine($"{callInfo.ProducedVar} = true;");
        ctx.AppendLine("cps.Push(new global::Fletched.Core.Runtime.ChoicePoint");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"LabelId = {_labelIds[blockLabel]},");
            ctx.AppendLine("TrailTop = state.Trail.Top");
        }
        ctx.AppendLine("});");
        ctx.AppendMetricIncrement("ChoicePointCount");
        ctx.AppendLine("observer?.OnChoicePoint();");

        for (int i = 0; i < call.ArgumentSlots.Count; i++)
        {
            int slot = call.ArgumentSlots[i];
            string slotName = SlotName(slot);
            string resultField = GetCallResultFieldName(call, i);
            EmitSlotConstUnify(slotName, $"{resultVar}.{resultField}", ctx);
        }
    }

    private int _notCounter;

    private void EmitNot(NotInstr not, EmitContext ctx)
    {
        if (not.SubGoalInstructions.Count == 0) return;

        // Single predicate call: check if any result matches the bound argument values.
        if (not.SubGoalInstructions.Count == 1 && not.SubGoalInstructions[0] is CallInstr call)
        {
            string predTypeName = call.PredicateType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string notFoundVar = $"_notFound_{_notCounter++}";
            string resultVar = $"_notResult_{call.PredicateType.Name}";
            ctx.AppendLine($"bool {notFoundVar} = false;");
            ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.EnterNegationScope(ctx);");
            ctx.AppendLine("try");
            ctx.AppendLine("{");
            using (ctx.Indent())
            {
                ctx.AppendLine($"foreach (var {resultVar} in default({predTypeName}).ExecuteArity{call.Arity}(ctx, null))");
                ctx.AppendLine("{");
                using (ctx.Indent())
                {
                    // Filter results by current bound values of the argument slots.
                    var conditions = new List<string>();
                    for (int i = 0; i < call.ArgumentSlots.Count; i++)
                    {
                        string slotName = SlotName(call.ArgumentSlots[i]);
                        string resultField = GetCallResultFieldName(call, i);
                        conditions.Add($"object.Equals(state.{slotName}, {resultVar}.{resultField})");
                    }
                    string guard = conditions.Count > 0
                        ? string.Join(" && ", conditions)
                        : "true";
                    ctx.AppendLine($"if ({guard}) {{ {notFoundVar} = true; break; }}");
                }
                ctx.AppendLine("}");
            }
            ctx.AppendLine("}");
            ctx.AppendLine("catch");
            ctx.AppendLine("{");
            using (ctx.Indent())
            {
                ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.ExitNegationScope(ctx);");
                ctx.AppendLine("throw;");
            }
            ctx.AppendLine("}");
            ctx.AppendLine("global::Fletched.Core.Runtime.RecursionGuard.ExitNegationScope(ctx);");
            ctx.AppendLine($"if ({notFoundVar}) goto Fail;");
            return;
        }

        // For inline instructions (unify/constraint/comp), build a compound boolean condition.
        // If ALL conditions hold, the subgoal succeeded → Not fails → goto Fail.
        var inlineConditions = new List<string>();
        foreach (PlanInstruction instr in not.SubGoalInstructions)
        {
            switch (instr)
            {
                case UnifyInstr u:
                    inlineConditions.Add($"object.Equals({EmitValue(u.Left)}, {EmitValue(u.Right)})");
                    break;

                case CompInstr c:
                    string op = c.Op switch
                    {
                        CompOp.NotEqual => "!=",
                        CompOp.LessThan => "<",
                        CompOp.GreaterThan => ">",
                        CompOp.LessThanOrEqual => "<=",
                        CompOp.GreaterThanOrEqual => ">=",
                        _ => "!="
                    };
                    inlineConditions.Add($"({EmitValue(c.Left)} {op} {EmitValue(c.Right)})");
                    break;

                case ConstraintInstr c2:
                    if (c2.Method.IsStatic)
                    {
                        string typeName = c2.Method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        string callArgs = string.Join(", ", c2.Arguments.Select(EmitValue));
                        inlineConditions.Add($"{typeName}.{c2.Method.Name}({callArgs})");
                    }
                    else if (c2.Arguments.Count > 0)
                    {
                        string receiver = EmitValue(c2.Arguments[0]);
                        string callArgs = string.Join(", ", c2.Arguments.Skip(1).Select(EmitValue));
                        string argStr = callArgs.Length > 0 ? callArgs : "";
                        inlineConditions.Add($"{receiver}.{c2.Method.Name}({argStr})");
                    }
                    break;
            }
        }

        if (inlineConditions.Count == 1)
            ctx.AppendLine($"if ({inlineConditions[0]}) goto Fail;");
        else if (inlineConditions.Count > 1)
            ctx.AppendLine($"if ({string.Join(" && ", inlineConditions)}) goto Fail;");
    }

    private void EmitUnify(UnifyInstr u, EmitContext ctx)
    {
        // Categorize left and right
        bool leftIsSlot = u.Left is SlotValue;
        bool rightIsSlot = u.Right is SlotValue;
        bool leftIsConst = u.Left is ConstValue;
        bool rightIsConst = u.Right is ConstValue;
        bool leftIsListLiteral = u.Left is ListConsValue or ListEmptyValue;
        bool rightIsListLiteral = u.Right is ListConsValue or ListEmptyValue;

        if (leftIsSlot && rightIsConst)
        {
            string slotName = SlotName(((SlotValue)u.Left).Slot);
            string constVal = EmitValue(u.Right);
            EmitSlotConstUnify(slotName, constVal, ctx);
        }
        else if (leftIsConst && rightIsSlot)
        {
            string slotName = SlotName(((SlotValue)u.Right).Slot);
            string constVal = EmitValue(u.Left);
            EmitSlotConstUnify(slotName, constVal, ctx);
        }
        else if (leftIsSlot && rightIsSlot)
        {
            string a = SlotName(((SlotValue)u.Left).Slot);
            string b = SlotName(((SlotValue)u.Right).Slot);
            EmitSlotSlotUnify(a, b, ctx);
        }
        else if (u.Left is FieldValue && rightIsSlot)
        {
            string slotName = SlotName(((SlotValue)u.Right).Slot);
            string fieldVal = EmitValue(u.Left);
            ctx.AppendLine($"{{ var _fv = {fieldVal};");
            using (ctx.Indent())
                EmitSlotConstUnify(slotName, "_fv", ctx);
            ctx.AppendLine("}");
        }
        else if (leftIsSlot && u.Right is FieldValue)
        {
            string slotName = SlotName(((SlotValue)u.Left).Slot);
            string fieldVal = EmitValue(u.Right);
            ctx.AppendLine($"{{ var _fv = {fieldVal};");
            using (ctx.Indent())
                EmitSlotConstUnify(slotName, "_fv", ctx);
            ctx.AppendLine("}");
        }
        else if (u.Left is FieldValue && u.Right is FieldValue)
        {
            ctx.AppendLine($"if ({EmitValue(u.Left)} != {EmitValue(u.Right)}) goto Fail;");
        }
        else if (leftIsSlot && rightIsListLiteral)
        {
            string slotName = SlotName(((SlotValue)u.Left).Slot);
            EmitSlotConstUnify(slotName, EmitValue(u.Right), ctx);
        }
        else if (leftIsListLiteral && rightIsSlot)
        {
            string slotName = SlotName(((SlotValue)u.Right).Slot);
            EmitSlotConstUnify(slotName, EmitValue(u.Left), ctx);
        }
        else if ((u.Left is FieldValue && rightIsListLiteral) ||
                 (leftIsListLiteral && u.Right is FieldValue))
        {
            ctx.AppendLine($"if (!object.Equals({EmitValue(u.Left)}, {EmitValue(u.Right)})) goto Fail;");
        }
        else if (u.Left is ArithValue || u.Right is ArithValue)
        {
            // Arithmetic expression on either side: use direct numeric equality.
            ctx.AppendLine($"if ({EmitValue(u.Left)} != {EmitValue(u.Right)}) goto Fail;");
        }
        else
        {
            // Generic fallback: emit as equality check
            ctx.AppendLine($"if (!object.Equals({EmitValue(u.Left)}, {EmitValue(u.Right)})) goto Fail;");
        }
    }

    private void EmitSlotConstUnify(string slotName, string value, EmitContext ctx)
    {
        int slot = _slots.First(s => s.Name == slotName).Slot;
        ctx.AppendMetricIncrement("UnifyAttempts");
        ctx.AppendLine($"observer?.OnUnify({slot});");
        ctx.AppendLine($"if (!state.{slotName}_bound)");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"state.Trail.Push({slot}, false);");
            ctx.AppendLine($"state.{slotName} = {value};");
            ctx.AppendLine($"state.{slotName}_bound = true;");
        }
        ctx.AppendLine("}");
        ctx.AppendLine($"else if (!object.Equals(state.{slotName}, {value}))");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendMetricIncrement("UnifyFailures");
            ctx.AppendLine($"observer?.OnUnifyFailure({slot});");
            ctx.AppendLine("goto Fail;");
        }
        ctx.AppendLine("}");
    }

    private void EmitSlotSlotUnify(string a, string b, EmitContext ctx)
    {
        int slotA = _slots.First(s => s.Name == a).Slot;
        int slotB = _slots.First(s => s.Name == b).Slot;
        ctx.AppendMetricIncrement("UnifyAttempts");
        ctx.AppendLine($"observer?.OnUnify({slotA});");
        ctx.AppendLine($"if (!state.{a}_bound && !state.{b}_bound) {{ /* both unbound - no-op */ }}");
        ctx.AppendLine($"else if (!state.{a}_bound)");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"state.Trail.Push({slotA}, false);");
            ctx.AppendLine($"state.{a} = state.{b};");
            ctx.AppendLine($"state.{a}_bound = true;");
        }
        ctx.AppendLine("}");
        ctx.AppendLine($"else if (!state.{b}_bound)");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendLine($"state.Trail.Push({slotB}, false);");
            ctx.AppendLine($"state.{b} = state.{a};");
            ctx.AppendLine($"state.{b}_bound = true;");
        }
        ctx.AppendLine("}");
        ctx.AppendLine($"else if (!object.Equals(state.{a}, state.{b}))");
        ctx.AppendLine("{");
        using (ctx.Indent())
        {
            ctx.AppendMetricIncrement("UnifyFailures");
            ctx.AppendLine($"observer?.OnUnifyFailure({slotA});");
            ctx.AppendLine("goto Fail;");
        }
        ctx.AppendLine("}");
    }

    private void EmitConstraint(ConstraintInstr c, EmitContext ctx)
    {
        string receiver = string.Empty;
        string callArgs = string.Empty;

        if (c.Method.IsStatic)
        {
            string typeName = c.Method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            callArgs = string.Join(", ", c.Arguments.Select(EmitValue));
            ctx.AppendLine($"if (!{typeName}.{c.Method.Name}({callArgs})) goto Fail;");
        }
        else
        {
            // Instance method: first arg is receiver
            if (c.Arguments.Count > 0)
            {
                receiver = EmitValue(c.Arguments[0]);
                callArgs = string.Join(", ", c.Arguments.Skip(1).Select(EmitValue));
                string argStr = callArgs.Length > 0 ? callArgs : "";
                ctx.AppendLine($"if (!{receiver}.{c.Method.Name}({argStr})) goto Fail;");
            }
        }
    }

    private void EmitComp(CompInstr comp, EmitContext ctx)
    {
        string left = EmitValue(comp.Left);
        string right = EmitValue(comp.Right);
        string op = comp.Op switch
        {
            CompOp.NotEqual => "!=",
            CompOp.LessThan => "<",
            CompOp.GreaterThan => ">",
            CompOp.LessThanOrEqual => "<=",
            CompOp.GreaterThanOrEqual => ">=",
            _ => "!="
        };
        ctx.AppendLine($"if (!({left} {op} {right})) goto Fail;");
    }

    private void EmitTerminator(PlanTerminator term, string blockLabel, EmitContext ctx)
    {
        switch (term)
        {
            case GotoTerm g:
                ctx.AppendLine($"goto L_{g.TargetLabel};");
                break;

            case ChoiceTerm choice:
            {
                int altId = _labelIds.TryGetValue(choice.AlternativeLabel, out int id) ? id : -1;
                ctx.AppendMetricIncrement("ChoicePointCount");
                ctx.AppendLine("observer?.OnChoicePoint();");
                ctx.AppendLine($"cps.Push(new global::Fletched.Core.Runtime.ChoicePoint {{ LabelId = {altId}, TrailTop = state.Trail.Top }});");
                ctx.AppendLine($"goto L_{choice.NextLabel};");
                break;
            }

            case SucceedTerm:
                ctx.AppendLine("goto Success;");
                break;

            case FailTerm:
                ctx.AppendLine("goto Fail;");
                break;

            case LoopCheckTerm lc:
                EmitLoopCheck(lc, ctx);
                break;
        }
    }

    private string EmitValue(PlanValue value)
    {
        return value switch
        {
            SlotValue sv => $"state.{SlotName(sv.Slot)}",
            ConstValue cv => EmitConstant(cv.Value, cv.TypeName),
            FieldValue fv => $"{EmitValue(fv.Target)}.{fv.MemberName}",
            ArithValue av => av.Op == ArithOp.Add
                ? $"({EmitValue(av.Left)} + {EmitValue(av.Right)})"
                : $"({EmitValue(av.Left)} - {EmitValue(av.Right)})",
            ListEmptyValue lev =>
                $"new global::Fletched.Core.LogicListEmpty<{lev.ElementTypeName}>()",
            ListConsValue lcv =>
                $"new global::Fletched.Core.LogicListCons<{lcv.ElementTypeName}>({EmitValue(lcv.Head)}, {EmitValue(lcv.Tail)})",
            _ => "default"
        };
    }

    private static string EmitConstant(object? value, string typeName)
    {
        if (value is null) return "null";
        if (value is string s) return $"\"{s.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"";
        if (value is bool b) return b ? "true" : "false";
        // For all other types (int, enum, etc.) emit an explicit cast to ensure type-safe
        // comparisons, particularly important for enum constants stored as their underlying
        // integer value (e.g. ClaimKind.Friend stored as 0 → "(ClaimKind)0").
        return $"({typeName}){value}";
    }

    private string SlotName(int slot)
    {
        var entry = _slots.FirstOrDefault(s => s.Slot == slot);
        return entry.Name ?? $"_slot{slot}";
    }

    private static string IndexMatchesVar(string indexVar) => $"{indexVar}_matches";

    private static void CollectSlots(
        PlanInstruction instruction,
        IDictionary<int, string> slotNames,
        IDictionary<int, string> slotTypes)
    {
        switch (instruction)
        {
            case UnifyInstr unify:
                CollectSlots(unify.Left, slotNames, slotTypes);
                CollectSlots(unify.Right, slotNames, slotTypes);
                break;

            case ConstraintInstr constraint:
                foreach (PlanValue argument in constraint.Arguments)
                    CollectSlots(argument, slotNames, slotTypes);
                break;

            case AssignInstr assign:
                AddIfMissing(slotNames, assign.Slot, $"_slot{assign.Slot}");
                AddIfMissing(slotTypes, assign.Slot, InferTypeName(assign.Value));
                CollectSlots(assign.Value, slotNames, slotTypes);
                break;

            case CompInstr comp:
                CollectSlots(comp.Left, slotNames, slotTypes);
                CollectSlots(comp.Right, slotNames, slotTypes);
                break;

            case LoopBindInstr bind:
                AddIfMissing(slotNames, bind.Slot, $"_slot{bind.Slot}");
                AddIfMissing(slotTypes, bind.Slot, bind.FactType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                if (bind.IndexedLookup is not null)
                    CollectSlots(bind.IndexedLookup.Key, slotNames, slotTypes);
                break;

            case IndexInitInstr init when init.IndexedLookup is not null:
                CollectSlots(init.IndexedLookup.Key, slotNames, slotTypes);
                break;

            case CallInstr call:
                foreach (int slot in call.ArgumentSlots)
                    AddIfMissing(slotNames, slot, $"_slot{slot}");
                break;

            case NotInstr not:
                foreach (PlanInstruction subGoalInstruction in not.SubGoalInstructions)
                    CollectSlots(subGoalInstruction, slotNames, slotTypes);
                break;
        }
    }

    private static void CollectSlots(
        PlanValue value,
        IDictionary<int, string> slotNames,
        IDictionary<int, string> slotTypes)
    {
        switch (value)
        {
            case SlotValue slot:
                AddIfMissing(slotNames, slot.Slot, $"_slot{slot.Slot}");
                AddIfMissing(slotTypes, slot.Slot, slot.TypeName);
                break;

            case FieldValue field:
                CollectSlots(field.Target, slotNames, slotTypes);
                break;

            case ArithValue arith:
                CollectSlots(arith.Left, slotNames, slotTypes);
                CollectSlots(arith.Right, slotNames, slotTypes);
                break;

            case ListConsValue cons:
                CollectSlots(cons.Head, slotNames, slotTypes);
                CollectSlots(cons.Tail, slotNames, slotTypes);
                break;
        }
    }

    private static string InferTypeName(PlanValue value)
    {
        return value switch
        {
            SlotValue slot => slot.TypeName,
            ConstValue constant => constant.TypeName,
            FieldValue field => field.TypeName,
            ArithValue arith => InferTypeName(arith.Left),
            ListEmptyValue empty => $"global::Fletched.Core.LogicList<{empty.ElementTypeName}>",
            ListConsValue cons => $"global::Fletched.Core.LogicList<{cons.ElementTypeName}>",
            _ => "object"
        };
    }

    private static void AddIfMissing(IDictionary<int, string> values, int key, string value)
    {
        if (!TryGetValue(values, key, out _))
            values[key] = value;
    }

    private static string ResolveSlotName(IDictionary<int, string> values, int key)
    {
        return TryGetValue(values, key, out string value)
            ? value
            : $"_slot{key}";
    }

    private static bool TryGetValue(IDictionary<int, string> values, int key, out string value)
    {
        if (values.TryGetValue(key, out string? existing) && existing is not null)
        {
            value = existing;
            return true;
        }

        value = string.Empty;
        return false;
    }

    private static string GetCallResultTypeName(CallInstr call)
    {
        bool singleArityPredicate = call.PredicateType.GetMembers()
            .OfType<IMethodSymbol>()
            .Count(method => method.GetAttributes().Any(attr => attr.AttributeClass?.Name == "PredicateBodyAttribute")) == 1;

        string resultTypeName = singleArityPredicate
            ? $"{call.PredicateType.Name}Result"
            : $"{call.PredicateType.Name}Arity{call.Arity}Result";

        return SourceSymbolHelpers.GetQualifiedSiblingTypeName(call.PredicateType, resultTypeName);
    }

    private static string GetCallResultFieldName(CallInstr call, int argumentIndex)
    {
        IMethodSymbol bodyMethod = ResolvePredicateBodyMethod(call.PredicateType, call.Arity);

        return bodyMethod.Parameters[argumentIndex].Name;
    }

    private static IMethodSymbol ResolvePredicateBodyMethod(INamedTypeSymbol predicateType, int arity)
    {
        return predicateType.GetMembers()
            .OfType<IMethodSymbol>()
            .Single(method =>
                method.GetAttributes().Any(attr => attr.AttributeClass?.Name == "PredicateBodyAttribute")
                && method.Parameters.Length == arity);
    }

    private static ITypeSymbol GetPredicateParameterValueType(IParameterSymbol parameter)
    {
        if (parameter.Type is INamedTypeSymbol namedType &&
            namedType.Name == "TerminalVar" &&
            namedType.TypeArguments.Length == 1)
        {
            return namedType.TypeArguments[0];
        }

        return parameter.Type;
    }

    private static IEnumerable<CallExpr> CollectCallExpressions(SemanticExpr expr)
    {
        switch (expr)
        {
            case CallExpr call:
                yield return call;
                foreach (SemanticExpr argument in call.Arguments)
                {
                    foreach (CallExpr nested in CollectCallExpressions(argument))
                        yield return nested;
                }
                 yield break;

            case FieldExpr field:
                foreach (CallExpr nested in CollectCallExpressions(field.Target))
                    yield return nested;
                yield break;

            case UnifyExpr unify:
                foreach (CallExpr nested in CollectCallExpressions(unify.Left))
                    yield return nested;
                foreach (CallExpr nested in CollectCallExpressions(unify.Right))
                    yield return nested;
                yield break;

            case ConjExpr conjunction:
                foreach (SemanticExpr part in conjunction.Parts)
                {
                    foreach (CallExpr nested in CollectCallExpressions(part))
                        yield return nested;
                }
                yield break;

            case DisjExpr disjunction:
                foreach (CallExpr nested in CollectCallExpressions(disjunction.Left))
                    yield return nested;
                foreach (CallExpr nested in CollectCallExpressions(disjunction.Right))
                    yield return nested;
                yield break;

            case ConstraintExpr constraint:
                foreach (SemanticExpr argument in constraint.Arguments)
                {
                    foreach (CallExpr nested in CollectCallExpressions(argument))
                        yield return nested;
                }
                yield break;

            case WithExpr withExpr:
                foreach (CallExpr nested in CollectCallExpressions(withExpr.Body))
                    yield return nested;
                yield break;

            case NotExpr notExpr:
                foreach (CallExpr nested in CollectCallExpressions(notExpr.Goal))
                    yield return nested;
                yield break;

            case CompExpr comp:
                foreach (CallExpr nested in CollectCallExpressions(comp.Left))
                    yield return nested;
                foreach (CallExpr nested in CollectCallExpressions(comp.Right))
                    yield return nested;
                yield break;

            case ArithExpr arith:
                foreach (CallExpr nested in CollectCallExpressions(arith.Left))
                    yield return nested;
                foreach (CallExpr nested in CollectCallExpressions(arith.Right))
                    yield return nested;
                yield break;

            case ListConsExpr listCons:
                foreach (CallExpr nested in CollectCallExpressions(listCons.Head))
                    yield return nested;
                foreach (CallExpr nested in CollectCallExpressions(listCons.Tail))
                    yield return nested;
                yield break;
        }
    }

    private static string TablePropertyName(ITypeSymbol factType)
    {
        // Generates the property name e.g. "User" → "Users"
        string name = factType.Name;
        return name.EndsWith("s") ? name : name + "s";
    }

    private static string Capitalize(string s) =>
        s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);
